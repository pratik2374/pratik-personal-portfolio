export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  // Global WebSite & Person Schema for Extreme Search Ranking
  const profile = await getProfile();
  const isPreview = (await draftMode()).isEnabled;

  const globalSchema = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "WebSite",
        "@id": `${baseUrl}/#website`,
        "url": baseUrl,
        "name": "Pratik Gond Blog",
        "description": "Technical deep dives into Artificial Intelligence, autonomous agents, and systems architecture.",
        "inLanguage": "en-US",
        "publisher": { "@id": PERSON_ID },
        "author": { "@id": PERSON_ID },
      },
      {
        "@type": "Blog",
        "@id": `${baseUrl}/#blog`,
        "url": baseUrl,
        "name": "Pratik Gond | Engineering, AI & Architecture Journal",
        "inLanguage": "en-US",
        "author": { "@id": PERSON_ID },
        "isPartOf": { "@id": `${baseUrl}/#website` },
      },
      {
        // Same @id the portfolio uses, so search engines treat blog + portfolio as one person.
        "@type": "Person",
        "@id": PERSON_ID,
        "name": profile.name,
        "url": profile.url,
        "jobTitle": profile.jobTitle,
        "description": profile.bio,
        "sameAs": profile.sameAs,
        "knowsAbout": ["Large Language Models", "Retrieval-Augmented Generation", "Generative AI", "AI Agents", "Software Architecture", "System Design", "Next.js", "Python", "C++"],
        ...(profile.location && { "homeLocation": { "@type": "Place", "name": profile.location } }),
      },
    ],
  };

  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: jsonLd(globalSchema) }}
        />
      </head>
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased bg-white dark:bg-[#0f0f0f] text-gray-900 dark:text-gray-100 transition-colors duration-200 min-h-screen flex flex-col font-sans selection:bg-orange-500 selection:text-white`}
      >
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem
        >
          <a
            href="#main-content"
            className="sr-only focus:not-sr-only focus:fixed focus:top-3 focus:left-3 focus:z-[100] focus:px-4 focus:py-2 focus:rounded-lg focus:bg-orange-500 focus:text-white focus:font-medium"
          >
            Skip to content
          </a>
          <Header />
          <main id="main-content" className="flex-1">{children}</main>
          <Footer />
          {isPreview && (
            <>
              <PreviewBanner />
              <VisualEditing />
            </>
          )}
        </ThemeProvider>
      </body>
    </html>
  );
}
